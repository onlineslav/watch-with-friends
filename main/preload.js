const {contextBridge, ipcRenderer, webUtils} = require('electron')

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  getVersion: () => ipcRenderer.invoke('app:version'),
  openProject: () => ipcRenderer.invoke('app:open-project'),
  chooseMedia: () => ipcRenderer.invoke('dialog:media'),
  youTubeTitles: (ids) => ipcRenderer.invoke('youtube:titles', ids),
  chooseMediaFiles: () => ipcRenderer.invoke('dialog:media-files'),
  chooseSubtitle: () => ipcRenderer.invoke('dialog:subtitle'),
  downloadInfo: (filePath) => ipcRenderer.invoke('download:info', filePath),
  downloadOpen: (filePath, size) => ipcRenderer.invoke('download:open', filePath, size),
  downloadRead: (id, offset) => ipcRenderer.invoke('download:read', id, offset),
  downloadSave: (info) => ipcRenderer.invoke('download:save', info),
  downloadWrite: (id, offset, bytes) => ipcRenderer.invoke('download:write', id, offset, bytes),
  downloadFinish: (id) => ipcRenderer.invoke('download:finish', id),
  downloadCancel: (id) => ipcRenderer.invoke('download:cancel', id),
  pathForFile: (file) => webUtils.getPathForFile(file),
  probe: (filePath) => ipcRenderer.invoke('media:probe', filePath),
  availableFiles: (paths) => ipcRenderer.invoke('media:available-files', paths),
  readImage: (filePath) => ipcRenderer.invoke('media:image', filePath),
  findIntro: (filePath) => ipcRenderer.invoke('media:intro', filePath),
  screenShareSources: () => ipcRenderer.invoke('screenshare:sources'),
  selectScreenShareSource: (id, options) => ipcRenderer.invoke('screenshare:select', id, options),
  startAppWindows: (sourceId) => ipcRenderer.invoke('appwindows:start', sourceId),
  grantAppWindow: (id, hwnd) => ipcRenderer.invoke('appwindows:grant', id, hwnd),
  grantSystemAudio: () => ipcRenderer.invoke('appwindows:system-audio'),
  pullAppWindows: (id) => ipcRenderer.invoke('appwindows:pull', id),
  stopAppWindows: (id) => ipcRenderer.invoke('appwindows:stop', id),
  startAppAudio: (windowId) => ipcRenderer.invoke('appaudio:start', windowId),
  pullAppAudio: (id) => ipcRenderer.invoke('appaudio:pull', id),
  stopAppAudio: (id) => ipcRenderer.invoke('appaudio:stop', id),
  startSession: (options) => ipcRenderer.invoke('session:start', options),
  pull: (sessionId) => ipcRenderer.invoke('session:pull', sessionId),
  stopSession: (sessionId) => ipcRenderer.invoke('session:stop', sessionId),
  subtitleCues: (options) => ipcRenderer.invoke('subtitle:cues', options),
  iceServers: () => ipcRenderer.invoke('net:ice-servers'),
  setPinned: (pinned) => ipcRenderer.invoke('window:pin', pinned),
  setZoom: (factor) => ipcRenderer.invoke('window:zoom', factor),
  onZoomStep: (handler) => ipcRenderer.on('zoom:step', (_event, direction) => handler(direction)),
  setInRoom: (inRoom) => ipcRenderer.send('app:in-room', inRoom),
  netProbePeers: (list) => ipcRenderer.send('netprobe:peers', list),
  netProbeTrouble: (peer, why) => ipcRenderer.send('netprobe:trouble', peer, why),
  onMachineSample: (handler) => ipcRenderer.on('machine:sample', (_event, reading) => handler(reading)),
  logEvents: (entries) => ipcRenderer.invoke('log:events', entries),
  saveDiagnostics: (options) => ipcRenderer.invoke('log:save', options),
  telemetryStatus: () => ipcRenderer.invoke('telemetry:status'),
  setTelemetry: (options) => ipcRenderer.invoke('telemetry:set', options),
  checkForUpdate: () => ipcRenderer.invoke('update:check'),
  retryUpdate: () => ipcRenderer.invoke('update:retry'),
  onUpdate: (handler) => {
    const listener = (_event, status) => handler(status)
    ipcRenderer.on('update:status', listener)
    return () => ipcRenderer.removeListener('update:status', listener)
  },
})
